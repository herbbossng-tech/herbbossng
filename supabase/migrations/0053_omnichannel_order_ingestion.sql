select r.id, p.id from public.roles r cross join public.permissions p
where r.workspace_id is null and r.slug in ('manager', 'marketing', 'viewer') and p.module = 'order_ingestion' and p.action = 'view'
on conflict do nothing;


-- ----------------------------------------------------------------
-- PART C — external_connections: one row per brand+provider. Exact
-- brand_communication_secrets discipline — RLS enabled, ZERO client
-- policies, unreachable from the frontend except through the RPCs in
-- PART G, and never through a raw select.
-- ----------------------------------------------------------------
create table public.external_connections (
  id uuid primary key default gen_random_uuid(),
  workspace_id uuid not null references public.workspaces (id) on delete cascade,
  brand_id uuid not null references public.brands (id) on delete cascade,
  provider text not null check (provider in ('shopify', 'woocommerce', 'google_sheets')),

  status text not null default 'disconnected' check (status in ('disconnected', 'connected', 'error')),
  last_error text,
  last_sync_at timestamptz,
  -- Free-form per-provider incremental-sync checkpoint (WooCommerce:
  -- {"after": "<ISO8601>"}; Google Sheets: {"last_row": 42}). Shopify
  -- is webhook-push and never needs one.
  sync_cursor jsonb not null default '{}'::jsonb,

  -- Shopify: a custom/private app's Admin API access token plus the
  -- app's own API secret (used only to verify X-Shopify-Hmac-Sha256 on
  -- inbound webhooks — never sent anywhere).
  shopify_shop_domain text,
  shopify_access_token text,
  shopify_api_secret text,

  -- WooCommerce: REST API v3 key pair (Basic Auth over HTTPS).
  woocommerce_store_url text,
  woocommerce_consumer_key text,
  woocommerce_consumer_secret text,

  -- Google Sheets: real OAuth (authorization-code flow), never a
  -- pasted access token — access tokens expire in ~1 hour, so the
  -- refresh_token is the credential that actually matters here.
  google_refresh_token text,
  google_access_token text,
  google_access_token_expires_at timestamptz,
  google_spreadsheet_id text,
  google_sheet_name text,
  google_column_mapping jsonb not null default '{}'::jsonb,
  google_header_row boolean not null default true,

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  created_by uuid references auth.users (id),
  updated_by uuid references auth.users (id),
  unique (brand_id, provider)
);

comment on table public.external_connections is
  'One row per brand+provider external order source. RLS enabled with NO policies for any client role — the exact brand_communication_secrets (0032) discipline: reachable only via upsert_external_connection()/disconnect_external_connection() (write, secrets never echoed back), get_external_connections() (read, secrets omitted entirely), and the service-role-only resolvers in PART H used by the ingestion Edge Functions. Never select this table directly from the frontend.';

