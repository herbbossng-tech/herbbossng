-- ================================================================
-- PART F — the shared ingestion pipeline. EVERY provider (Shopify
-- webhook, WooCommerce sync worker, Google Sheets sync worker, and
-- any future source) funnels through ingest_external_order() with
-- one normalized shape:
--   p_customer: {name, phone, email, country_code, state, city,
--                address, address_2, postal_code}
--   p_items:    [{external_product_id, external_variant_id,
--                 external_sku, name, quantity, unit_price}, ...]
-- Provider-specific parsing (Shopify's nested line_items, WooCommerce's
-- billing/shipping split, a Sheets row's mapped columns) all happens
-- in the calling Edge Function — this function never knows or cares
-- which provider produced the shape.
-- ================================================================
create or replace function public.ingest_external_order(
  p_connection_id uuid,
  p_external_order_id text,
  p_external_order_number text,
  p_customer jsonb,
  p_items jsonb,
  p_shipping_fee numeric default 0,
  p_discount_amount numeric default 0,
  p_currency_code text default null,
  p_source_detail text default null,
  p_raw_payload jsonb default '{}'::jsonb
)
returns public.external_order_ingestion_log
language plpgsql
security definer
set search_path = public
as $$
declare
  v_conn public.external_connections%rowtype;
  v_log public.external_order_ingestion_log%rowtype;
begin
  if coalesce(trim(p_external_order_id), '') = '' then
    raise exception 'external_order_id is required';
  end if;

  select * into v_conn from public.external_connections where id = p_connection_id;
  if not found then
    raise exception 'Unknown connection %', p_connection_id;
  end if;

  -- Idempotency: exactly one row per (connection_id, external_order_id)
  -- ever gets created. A brand-new order takes this branch.
  insert into public.external_order_ingestion_log (
    workspace_id, brand_id, connection_id, provider, external_order_id, external_order_number,
    status, input_customer, input_items, input_shipping_fee, input_discount_amount,
    input_currency_code, input_source_detail, raw_payload
  ) values (
    v_conn.workspace_id, v_conn.brand_id, p_connection_id, v_conn.provider, trim(p_external_order_id), nullif(p_external_order_number, ''),
    'pending', coalesce(p_customer, '{}'::jsonb), coalesce(p_items, '[]'::jsonb), coalesce(p_shipping_fee, 0), coalesce(p_discount_amount, 0),
    p_currency_code, p_source_detail, coalesce(p_raw_payload, '{}'::jsonb)
  )
  on conflict (connection_id, external_order_id) do nothing
  returning * into v_log;

  if v_log.id is not null then
    return public.process_external_order_ingestion(v_log.id);
  end if;

  -- Already seen this external_order_id before — decide whether THIS
  -- call should reprocess the existing row.
  select * into v_log from public.external_order_ingestion_log
    where connection_id = p_connection_id and external_order_id = trim(p_external_order_id);

  if v_log.status = 'processing' and v_log.claimed_at < now() - interval '10 minutes' then
    -- A prior attempt crashed mid-transaction (or the Edge Function
    -- itself died) without ever reaching a terminal status — same
    -- 10-minute reclaim window as communication_log/tracking_dispatch_log.
    return public.process_external_order_ingestion(v_log.id);
  end if;

  if v_log.status = 'failed' and (v_log.next_retry_at is null or v_log.next_retry_at <= now()) then
    -- A repeat delivery of a previously-failed webhook (Shopify retries
    -- failed webhooks automatically) or a re-fetch of a row that failed
    -- last sync is a legitimate, free retry opportunity — take it,
    -- respecting the same backoff window a scheduled retry would.
    return public.process_external_order_ingestion(v_log.id);
  end if;

  -- ingested / needs_review / a fresh processing row / a failed row
  -- still inside its backoff window: never reprocessed by a repeat
  -- delivery. needs_review in particular must wait for a human
  -- (retry_external_order_ingestion), never silently retried with the
  -- same unresolved items.
  return v_log;
end;
$$;

revoke execute on function public.ingest_external_order(uuid, text, text, jsonb, jsonb, numeric, numeric, text, text, jsonb) from public, anon, authenticated;

comment on function public.ingest_external_order(uuid, text, text, jsonb, jsonb, numeric, numeric, text, text, jsonb) is
  'The single entry point every provider adapter calls (Shopify webhook, WooCommerce sync worker, Google Sheets sync worker). Never callable by anon/authenticated — only a service-role Edge Function that has already verified the request''s legitimacy (Shopify HMAC, WooCommerce Basic Auth, a valid Google access token) may call this. Idempotent on (connection_id, external_order_id) forever; see process_external_order_ingestion() for the actual customer/product/order pipeline.';


create or replace function public.process_external_order_ingestion(p_log_id uuid)
returns public.external_order_ingestion_log
language plpgsql
security definer
set search_path = public
as $$
declare
  v_log public.external_order_ingestion_log%rowtype;
  v_conn public.external_connections%rowtype;
  v_workspace_currency text;
  v_workspace_country text;
  v_dial_code text;
  v_canonical_phone text;
  v_first_name text;
  v_last_name text;
  v_customer_name text;
  v_customer_id uuid;
  v_is_repeat boolean;
  v_item jsonb;
  v_resolved_product_id uuid;
  v_resolved_name text;
  v_resolved_sku text;
  v_resolved_cost numeric;
  v_quantity integer;
  v_unit_price numeric;
  v_unresolved jsonb := '[]'::jsonb;
  v_normalized_items jsonb := '[]'::jsonb;
  v_subtotal numeric := 0;
  v_cost numeric := 0;
  v_total numeric;
  v_currency text;
  v_order_number text;
  v_order public.orders%rowtype;
  v_dup_order_number text;
  v_dup_created_at timestamptz;
  v_possible_duplicate boolean := false;
  v_next_attempts integer;
begin
  select * into v_log from public.external_order_ingestion_log where id = p_log_id for update;
  if not found then
    raise exception 'Ingestion log row % not found', p_log_id;
  end if;

  select * into v_conn from public.external_connections where id = v_log.connection_id;
  if not found then
    raise exception 'Connection % no longer exists', v_log.connection_id;
  end if;

  v_next_attempts := v_log.attempts + 1;
  update public.external_order_ingestion_log
    set status = 'processing', attempts = v_next_attempts, claimed_at = now(), claimed_by = 'inline', updated_at = now()
    where id = p_log_id;

  begin
    select currency_code, country_code into v_workspace_currency, v_workspace_country
      from public.workspaces where id = v_conn.workspace_id;

    select dial_code into v_dial_code from public.countries
      where code = coalesce(nullif(v_log.input_customer ->> 'country_code', ''), v_workspace_country);

    v_canonical_phone := public.normalize_phone(v_log.input_customer ->> 'phone', v_dial_code);
    if v_canonical_phone is null then
      raise exception 'A valid customer phone number is required to ingest an order';
    end if;

    v_customer_name := trim(nullif(v_log.input_customer ->> 'name', ''));
    if v_customer_name is null or v_customer_name = '' then
      v_customer_name := 'Customer ' || v_log.external_order_number;
    end if;
    v_first_name := split_part(v_customer_name, ' ', 1);
    v_last_name := nullif(trim(substring(v_customer_name from length(v_first_name) + 1)), '');

    select id into v_customer_id from public.customers
      where workspace_id = v_conn.workspace_id and brand_id = v_conn.brand_id
        and canonical_phone = v_canonical_phone and deleted_at is null;

    if not found then
      insert into public.customers (
        workspace_id, brand_id, first_name, last_name, full_name, phone, canonical_phone,
        email, country_code, state, city, address, address_2, postal_code, acquisition_source
      ) values (
        v_conn.workspace_id, v_conn.brand_id, v_first_name, v_last_name, v_customer_name,
        v_log.input_customer ->> 'phone', v_canonical_phone,
        nullif(v_log.input_customer ->> 'email', ''), coalesce(nullif(v_log.input_customer ->> 'country_code', ''), v_workspace_country),
        v_log.input_customer ->> 'state', v_log.input_customer ->> 'city', coalesce(v_log.input_customer ->> 'address', ''),
        v_log.input_customer ->> 'address_2', v_log.input_customer ->> 'postal_code', v_conn.provider
      )
      on conflict (workspace_id, brand_id, canonical_phone) where deleted_at is null
        do update set updated_at = now()
      returning id into v_customer_id;
    end if;

    select exists(
      select 1 from public.orders where customer_id = v_customer_id and deleted_at is null
    ) into v_is_repeat;

    -- Same possible-duplicate definition as create_order()/create_public_order()
    -- (0052): another non-cancelled/non-returned order from this same
    -- customer in the last 24 hours.
    select o.order_number, o.created_at into v_dup_order_number, v_dup_created_at
      from public.orders o
      where o.customer_id = v_customer_id and o.deleted_at is null
        and o.status not in ('CANCELLED', 'RETURNED')
        and o.created_at > now() - interval '24 hours'
      order by o.created_at desc
      limit 1;
    v_possible_duplicate := found;

    -- Deterministic product resolution — never guess. A single
    -- unresolved item routes the WHOLE order to needs_review, since a
    -- partially-created order would misstate its own total.
    v_unresolved := '[]'::jsonb;
    v_normalized_items := '[]'::jsonb;
    v_subtotal := 0;
    v_cost := 0;

    for v_item in select * from jsonb_array_elements(coalesce(v_log.input_items, '[]'::jsonb))
    loop
      v_quantity := greatest(coalesce((v_item ->> 'quantity')::integer, 1), 1);
      v_unit_price := coalesce((v_item ->> 'unit_price')::numeric, 0);
      v_resolved_product_id := null;

      select product_id into v_resolved_product_id from public.external_product_mappings
        where connection_id = v_log.connection_id
          and coalesce(external_product_id, '') = coalesce(v_item ->> 'external_product_id', '')
          and coalesce(external_variant_id, '') = coalesce(v_item ->> 'external_variant_id', '');

      if v_resolved_product_id is null and coalesce(v_item ->> 'external_sku', '') <> '' then
        select id into v_resolved_product_id from public.products
          where brand_id = v_conn.brand_id and sku = (v_item ->> 'external_sku') and deleted_at is null;
      end if;

      if v_resolved_product_id is null then
        v_unresolved := v_unresolved || jsonb_build_array(v_item);
      else
        select name, sku, cost_price into v_resolved_name, v_resolved_sku, v_resolved_cost
          from public.products where id = v_resolved_product_id;
        v_normalized_items := v_normalized_items || jsonb_build_array(jsonb_build_object(
          'product_id', v_resolved_product_id, 'name', v_resolved_name, 'sku', v_resolved_sku,
          'quantity', v_quantity, 'unit_price', v_unit_price, 'unit_cost', coalesce(v_resolved_cost, 0),
          'external_product_id', v_item ->> 'external_product_id', 'external_sku', v_item ->> 'external_sku'
        ));
        v_subtotal := v_subtotal + v_unit_price * v_quantity;
        v_cost := v_cost + coalesce(v_resolved_cost, 0) * v_quantity;
      end if;
    end loop;

    if jsonb_array_length(v_unresolved) > 0 then
      update public.external_order_ingestion_log
        set status = 'needs_review', unresolved_items = v_unresolved, normalized_items = v_normalized_items,
            error_message = 'unresolved_items: ' || jsonb_array_length(v_unresolved) || ' line item(s) could not be matched to a product',
            next_retry_at = null, updated_at = now()
        where id = p_log_id
        returning * into v_log;
      return v_log;
    end if;

    if jsonb_array_length(v_normalized_items) = 0 then
      raise exception 'Order has no items to ingest';
    end if;

    v_currency := coalesce(nullif(v_log.input_currency_code, ''), v_workspace_currency, 'USD');
    v_total := v_subtotal + v_log.input_shipping_fee - v_log.input_discount_amount;

    v_order_number := public.generate_order_number(v_conn.workspace_id);

    insert into public.orders (
      workspace_id, brand_id, order_number, source, status, priority,
      customer_id, customer_name, customer_phone, customer_email, customer_country_code,
      customer_state, customer_city, customer_address, customer_address_2, customer_postal_code,
      currency_code, subtotal, shipping_fee, discount_amount, total_amount, cost_amount, expected_profit,
      source_detail, is_repeat_customer,
      external_source, external_connection_id, external_order_id, external_order_number,
      metadata
    ) values (
      v_conn.workspace_id, v_conn.brand_id, v_order_number, v_conn.provider, 'NEW', 'normal',
      v_customer_id, v_customer_name, v_log.input_customer ->> 'phone', nullif(v_log.input_customer ->> 'email', ''),
      coalesce(nullif(v_log.input_customer ->> 'country_code', ''), v_workspace_country),
      v_log.input_customer ->> 'state', v_log.input_customer ->> 'city',
      coalesce(v_log.input_customer ->> 'address', ''), v_log.input_customer ->> 'address_2', v_log.input_customer ->> 'postal_code',
      v_currency, v_subtotal, v_log.input_shipping_fee, v_log.input_discount_amount, v_total, v_cost, v_subtotal - v_cost,
      coalesce(v_log.input_source_detail, initcap(replace(v_conn.provider, '_', ' '))), v_is_repeat,
      v_conn.provider, v_conn.id, v_log.external_order_id, v_log.external_order_number,
      jsonb_build_object(
        'item_summary', (select string_agg((i ->> 'name') || ' x' || (i ->> 'quantity'), ', ') from jsonb_array_elements(v_normalized_items) i),
        'item_quantity', (select sum((i ->> 'quantity')::integer) from jsonb_array_elements(v_normalized_items) i),
        'possible_duplicate', v_possible_duplicate,
        'duplicate_of_order_number', v_dup_order_number,
        'duplicate_minutes_ago', case when v_possible_duplicate then round(extract(epoch from (now() - v_dup_created_at)) / 60) else null end
      )
    )
    returning * into v_order;

    for v_item in select * from jsonb_array_elements(v_normalized_items)
    loop
      insert into public.order_items (
        order_id, workspace_id, brand_id, product_id, product_name, sku, quantity, unit_price, unit_cost, total_amount
      ) values (
        v_order.id, v_conn.workspace_id, v_conn.brand_id, (v_item ->> 'product_id')::uuid, v_item ->> 'name', v_item ->> 'sku',
        (v_item ->> 'quantity')::integer, (v_item ->> 'unit_price')::numeric, (v_item ->> 'unit_cost')::numeric,
        (v_item ->> 'unit_price')::numeric * (v_item ->> 'quantity')::integer
      );

      if (select track_inventory from public.products where id = (v_item ->> 'product_id')::uuid) then
        -- adjust_inventory_internal(), not adjust_inventory(): this
        -- pipeline runs SECURITY DEFINER with no auth.uid() at all
        -- (called from a service-role Edge Function, not a staff
        -- session) — the exact same reason create_public_order() calls
        -- the internal core directly (0031, PART E1).
        perform public.adjust_inventory_internal(
          (v_item ->> 'product_id')::uuid, 'RESERVED', (v_item ->> 'quantity')::integer,
          'Order ' || v_order_number || ' created (' || v_conn.provider || ')', 'order', v_order.id
        );
      end if;
    end loop;

    update public.external_order_ingestion_log
      set status = 'ingested', order_id = v_order.id, normalized_items = v_normalized_items, unresolved_items = null,
          error_message = null, next_retry_at = null, updated_at = now()
      where id = p_log_id
      returning * into v_log;

    update public.external_connections
      set status = 'connected', last_error = null, last_sync_at = now()
      where id = v_conn.id;

  exception when others then
    update public.external_order_ingestion_log
      set status = case when v_next_attempts >= max_attempts then 'permanently_failed' else 'failed' end,
          error_message = left(sqlerrm, 2000),
          next_retry_at = case when v_next_attempts >= max_attempts then null
            else now() + (least(power(2, v_next_attempts)::int * 30, 3600) || ' seconds')::interval end,
          updated_at = now()
      where id = p_log_id
      returning * into v_log;

    update public.external_connections
      set status = 'error', last_error = left(sqlerrm, 2000)
      where id = v_conn.id;
  end;

  return v_log;
end;
$$;

