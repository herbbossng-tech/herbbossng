-- ----------------------------------------------------------------
-- PART D — external_order_ingestion_log: the idempotency ledger,
-- audit trail, AND retry queue for every external order ingestion
-- attempt in one table (deliberately not split three ways — a
-- provider webhook re-delivery, a staff manual retry, and a scheduled
-- backoff retry are all just another call into the same pipeline
-- against the same row). input_* columns capture exactly what the
-- caller supplied so a retry never needs to re-fetch anything from
-- the provider; raw_payload is kept purely for audit/debugging and is
-- never re-parsed by the pipeline itself.
-- ----------------------------------------------------------------
create table public.external_order_ingestion_log (
  id uuid primary key default gen_random_uuid(),
  workspace_id uuid not null references public.workspaces (id) on delete cascade,
  brand_id uuid not null references public.brands (id) on delete cascade,
  connection_id uuid not null references public.external_connections (id) on delete cascade,
  provider text not null check (provider in ('shopify', 'woocommerce', 'google_sheets')),

  external_order_id text not null,
  external_order_number text,

  status text not null default 'pending' check (status in (
    'pending', 'processing', 'ingested', 'needs_review', 'failed', 'permanently_failed'
  )),
  order_id uuid references public.orders (id) on delete set null,

  input_customer jsonb not null default '{}'::jsonb,
  input_items jsonb not null default '[]'::jsonb,
  input_shipping_fee numeric(14, 2) not null default 0,
  input_discount_amount numeric(14, 2) not null default 0,
  input_currency_code text,
  input_source_detail text,
  raw_payload jsonb not null default '{}'::jsonb,

  normalized_items jsonb,
  unresolved_items jsonb,
  error_message text,

  attempts integer not null default 0,
  max_attempts integer not null default 5,
  next_retry_at timestamptz,
  claimed_at timestamptz,
  claimed_by text,

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

comment on table public.external_order_ingestion_log is
  'One row per (connection_id, external_order_id), forever — a re-delivered Shopify webhook, a re-fetched WooCommerce page, or a re-read Google Sheets row all resolve to this SAME row, never a duplicate order. needs_review rows hold at least one line item that could not be matched to an internal product (see PART F) and carry NO order_id — GCOS never guesses a product match. failed/permanently_failed rows follow the identical exponential-backoff discipline as communication_log/tracking_dispatch_log (0032).';

