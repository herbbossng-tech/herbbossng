create or replace function public.claim_external_ingestion_retry_batch(p_worker_id text, p_limit integer default 20)
returns setof uuid
language plpgsql
security definer
set search_path = public
as $$
begin
  return query
  with claimed as (
    select l.id from public.external_order_ingestion_log l
    where (l.status = 'failed' and l.next_retry_at <= now())
       or (l.status = 'processing' and l.claimed_at < now() - interval '10 minutes')
    order by l.created_at
    limit p_limit
    for update skip locked
  ),
  updated as (
    update public.external_order_ingestion_log l
      set claimed_at = now(), claimed_by = p_worker_id, updated_at = now()
      from claimed
      where l.id = claimed.id
      returning l.id
  )
  select id from updated;
end;
$$;

revoke execute on function public.claim_external_ingestion_retry_batch(text, integer) from public, anon, authenticated;

