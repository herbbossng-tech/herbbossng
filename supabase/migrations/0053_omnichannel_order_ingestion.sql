-- ============================================================
-- GOLDEN COMMERCE OS — Omnichannel Order Ingestion, Foundation
-- (0053): Shopify, WooCommerce, and Google Sheets as external order
-- sources feeding the SAME order engine every other channel already
-- uses (landing pages, manual entry, affiliates). No parallel order/
-- customer/inventory system is created here — every external order
-- ends up as one ordinary row in public.orders, created the same way
-- create_order()/create_public_order() already do: canonical-phone
-- customer resolution, live product pricing, adjust_inventory_internal()
-- for stock, and the existing emit_orders_created trigger, which means
-- automation rules, staff notifications, and the Integration Health
-- "Automation Retry Queue" all work on an ingested order with ZERO
-- additional wiring (see 0028's emit_order_created_event()).
--
-- Audited before writing a single line here (see the accompanying
-- engineering report): there is no existing Shopify/WooCommerce code
-- anywhere in this repo, no existing Google Sheets integration, no
-- external-order-id concept on orders, and the workspace->brand
-- hierarchy has no separate "market" entity — connections here are
-- brand-scoped, exactly like brand_communication_secrets/
-- brand_tracking_secrets (0031/0032), which this migration copies the
-- secret-storage discipline from verbatim: RLS enabled with NO client
-- policies, reachable only through SECURITY DEFINER RPCs, and a secret
-- value is never once returned to the browser.
--
-- Shape of this migration:
--   PART A — orders: new source values + external-id columns
--   PART B — permissions: order_ingestion.view / .manage
--   PART C — external_connections (brand-scoped provider secrets)
--   PART D — external_order_ingestion_log (idempotency + retry queue)
--   PART E — external_product_mappings (deterministic item resolution)
--   PART F — the shared ingestion pipeline (ingest_external_order /
--            process_external_order_ingestion) every provider calls
--   PART G — staff-facing RPCs (connect/disconnect/list/retry/map)
--   PART H — service-role-only RPCs for the ingestion Edge Functions
--   PART I — realtime
-- ============================================================


-- ----------------------------------------------------------------
-- PART A — orders: widen the source vocabulary, add external
-- reference columns. idempotency_key already protects against a
-- literal retry of the same submission; external_order_id is a
-- DIFFERENT concept — it is how GCOS recognizes "I have already
-- ingested Shopify order #1042 for this connection", independent of
-- anything GCOS itself generated.
-- ----------------------------------------------------------------
alter table public.orders
  add column if not exists external_source text,
  add column if not exists external_connection_id uuid,
  add column if not exists external_order_id text,
  add column if not exists external_order_number text;

alter table public.orders drop constraint orders_source_check;
alter table public.orders add constraint orders_source_check
  check (source in (
    'website', 'whatsapp', 'phone', 'facebook', 'instagram', 'tiktok',
    'walk_in', 'manual', 'affiliate', 'landing_page',
    'shopify', 'woocommerce', 'google_sheets', 'other'
  ));

create unique index orders_external_source_idx
  on public.orders (workspace_id, brand_id, external_source, external_order_id)
  where external_order_id is not null;

comment on column public.orders.external_source is
  'Set only for orders created by ingest_external_order() (''shopify''/''woocommerce''/''google_sheets''); null for every other channel. Mirrors orders.source but kept as its own column so a future rename of source''s vocabulary can never silently break ingestion idempotency.';
comment on column public.orders.external_order_id is
  'The foreign system''s own order id/number (e.g. a Shopify numeric order id, a WooCommerce order id, a Google Sheets row key) — never generated by GCOS. Unique per (workspace_id, brand_id, external_source, external_order_id); the actual dedup authority is external_order_ingestion_log''s unique (connection_id, external_order_id), enforced before this row ever gets inserted.';


-- ----------------------------------------------------------------
-- PART B — permissions. No existing per-provider permission exists
-- anywhere in GCOS (communications.* covers email+sms+whatsapp
